//! Explicit F32 range reduction and fused polynomial for periodic Hann coefficients.

/// This specialization is used only for Hann arguments in `[0, 2*pi]`, within
/// SLEEF's small-range branch. It has no arbitrary-angle fallback or native
/// vector-ABI dependence. Products outside the explicit `mul_add`s round in F32.
fn cosine(mut angle: f32) -> f32 {
    let quadrant =
        2 * ((angle * (1.0 / std::f64::consts::PI) as f32 - 0.5).round_ties_even() as i32) + 1;
    angle = (quadrant as f32).mul_add(-3.1414794921875f32 * 0.5, angle);
    angle = (quadrant as f32).mul_add(-0.00011315941810607910156f32 * 0.5, angle);
    angle = (quadrant as f32).mul_add(-1.9841872589410058936e-09f32 * 0.5, angle);
    let square = angle * angle;
    if quadrant & 2 == 0 {
        angle = -angle;
    }
    let mut polynomial = 2.6083159809786593541503e-06f32;
    polynomial = polynomial.mul_add(square, -0.0001981069071916863322258f32);
    polynomial = polynomial.mul_add(square, 0.00833307858556509017944336f32);
    polynomial = polynomial.mul_add(square, -0.166666597127914428710938f32);
    square * (polynomial * angle) + angle
}

pub(super) fn hann(length: i32) -> Vec<f32> {
    let step = (std::f64::consts::TAU / f64::from(length)) as f32;
    (0..length)
        .map(|i| -0.5 * cosine(i as f32 * step) + 0.5)
        .collect()
}
