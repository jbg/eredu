use std::any::TypeId;

#[test]
fn facade_exports_are_the_canonical_core_types() {
    assert_eq!(
        TypeId::of::<safemlx_lm::ModelKind>(),
        TypeId::of::<safemlx_lm::core::artifact::ModelKind>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::GgufArchitecture>(),
        TypeId::of::<safemlx_lm::core::artifact::GgufArchitecture>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::PreparationPolicy>(),
        TypeId::of::<safemlx_lm::core::artifact::PreparationPolicy>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::ModelPreparationPlan>(),
        TypeId::of::<safemlx_lm::core::artifact::ModelPreparationPlan>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::AttentionPolicy>(),
        TypeId::of::<safemlx_lm::core::attention::AttentionPolicy>(),
    );
    let schedule = safemlx_lm::LayerSchedule::all_full(2).unwrap();
    assert_eq!(schedule.len(), 2);
    assert_eq!(
        TypeId::of::<safemlx_lm::RequestId>(),
        TypeId::of::<safemlx_lm::core::scheduler::RequestId>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::SchedulerLimits>(),
        TypeId::of::<safemlx_lm::core::scheduler::SchedulerLimits>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::SchedulerReport>(),
        TypeId::of::<safemlx_lm::core::scheduler::SchedulerReport>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::SchedulerError>(),
        TypeId::of::<safemlx_lm::core::scheduler::SchedulerError>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::OffloadConfig>(),
        TypeId::of::<safemlx_lm::core::residency::OffloadConfig>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::MemoryTier>(),
        TypeId::of::<safemlx_lm::core::residency::MemoryTier>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::OffloadReport>(),
        TypeId::of::<safemlx_lm::core::residency::OffloadReport>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::ResidencyLedger>(),
        TypeId::of::<safemlx_lm::core::residency::ResidencyLedger>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::ResidencyLedgerError>(),
        TypeId::of::<safemlx_lm::core::residency::ResidencyLedgerError>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::UnitResidencyReport>(),
        TypeId::of::<safemlx_lm::core::residency::UnitResidencyReport>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::CachePoolLimits>(),
        TypeId::of::<safemlx_lm::core::cache::CachePoolLimits>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::CacheResidencyPool>(),
        TypeId::of::<safemlx_lm::core::cache::CacheResidencyPool>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::CachePoolReport>(),
        TypeId::of::<safemlx_lm::core::cache::CachePoolReport>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::CacheBlockId>(),
        TypeId::of::<safemlx_lm::core::cache::CacheBlockId>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::LayerCachePolicy>(),
        TypeId::of::<safemlx_lm::core::cache::LayerCachePolicy>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::StateTensorPolicy>(),
        TypeId::of::<safemlx_lm::core::cache::StateTensorPolicy>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::PromptCacheDescriptor>(),
        TypeId::of::<safemlx_lm::core::cache::PromptCacheDescriptor>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::PromptCacheManifest>(),
        TypeId::of::<safemlx_lm::core::cache::PromptCacheManifest>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::PromptCacheTopology>(),
        TypeId::of::<safemlx_lm::core::cache::PromptCacheTopology>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::CacheBlockLifecycle>(),
        TypeId::of::<safemlx_lm::core::cache::CacheBlockLifecycle>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::MutableCacheTail>(),
        TypeId::of::<safemlx_lm::core::cache::MutableCacheTail>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::CacheLifecycleError>(),
        TypeId::of::<safemlx_lm::core::cache::CacheLifecycleError>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::CacheStoragePhase>(),
        TypeId::of::<safemlx_lm::core::cache::CacheStoragePhase>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::CacheIoOperationKey>(),
        TypeId::of::<safemlx_lm::core::cache::CacheIoOperationKey>(),
    );
    assert_eq!(
        TypeId::of::<safemlx_lm::CacheStorageError>(),
        TypeId::of::<safemlx_lm::core::cache::CacheStorageError>(),
    );
}
