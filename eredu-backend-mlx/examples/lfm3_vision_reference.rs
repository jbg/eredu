fn sha256_file(path: &std::path::Path) -> Result<String, Box<dyn Error>> {
    let mut input = std::fs::File::open(path)?;
    let mut digest = Sha256::new();
    let mut buffer = [0u8; 65536];
    loop {
        let count = input.read(&mut buffer)?;
        if count == 0 {
            break;
        }
        digest.update(&buffer[..count]);
    }
    Ok(digest
        .finalize()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect())
}

fn pinned_gguf_digest(path: &std::path::Path, role: &str) -> Result<String, Box<dyn Error>> {
    let sha256 = sha256_file(path)?;
    let sources: Value = serde_json::from_str(include_str!(
        "../../validation/fixtures/lfm3/vision-gguf-sources.json"
    ))?;
    let entries = sources[role]
        .as_object()
        .ok_or("missing pinned GGUF identities")?;
    if !entries
        .values()
        .any(|entry| entry["publisher_sha256"].as_str() == Some(sha256.as_str()))
    {
        return Err(format!("GGUF digest differs from the pinned {role}").into());
    }
    Ok(sha256)
}

