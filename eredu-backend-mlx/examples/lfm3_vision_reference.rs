//! Released LFM3 vision-component acceptance against pinned publisher code.
//! This does not establish facade, conditional generation or distributed support.

use clap::Parser;
use eredu_architectures::lfm3::vision::{
    Declaration, ProjectorConfig, VisionBlock, VisionInput, VisionPatchifier, VisionProjector,
};
use eredu_backend_mlx::{
    backend::{
        nn::shared::MlxNeuralBackend,
        runtime::checkpoint::binding::{
            build_neutral_module_bindings_with_recipes, materialize_module_bindings,
            populate_module_from_arrays_excluding,
        },
        ExecutionContext,
    },
    MlxTensor,
};
use eredu_checkpoint::{
    safetensors::SafetensorsMetadataCatalog,
    store::{open_prepared_safetensors_source, CheckpointSource},
    validation::resolve_safetensors_plan,
};
use eredu_nn::{Parameterized, Tensor};
use safemlx::{Array, Device, DeviceType, Stream};
use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use std::io::Read;
use std::{collections::BTreeMap, error::Error, path::PathBuf};

type Backend = MlxNeuralBackend;

fn sha256_file(path: &std::path::Path) -> Result<String, Box<dyn Error>> {
    let mut input = std::fs::File::open(path)?;
    let mut digest = Sha256::new();
    let mut buffer = [0u8; 65536];
    loop {
        let count = input.read(&mut buffer)?;
        if count == 0 {
            break;
        }
        digest.update(&buffer[..count]);
    }
    Ok(digest
        .finalize()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect())
}

#[derive(Parser)]
struct Args {
    /// F32 component checkpoint generated by the pinned reference entry point.
    checkpoint: PathBuf,
    /// Directory containing reference.json and reference.safetensors.
    reference: PathBuf,
    /// Compact measured results, outside the source tree.
    output: PathBuf,
    /// Native device (Metal requires the feature and device access).
    #[arg(long, default_value="cpu", value_parser=["cpu","gpu"])]
    device: String,
}

fn load<M: Parameterized<MlxTensor>>(
    module: &mut M,
    source: &dyn CheckpointSource,
    source_stream: &Stream,
    stream: &Stream,
) -> Result<(), Box<dyn Error>> {
    let bindings =
        build_neutral_module_bindings_with_recipes(module, source, &mut BTreeMap::new())?;
    let arrays = materialize_module_bindings(source, &bindings, source_stream, stream)?;
    populate_module_from_arrays_excluding(module, &arrays, |_| false)?;
    Ok(())
}

fn compare(actual: &MlxTensor, expected: &Array, atol: f64) -> Result<Value, Box<dyn Error>> {
    if actual.shape() != expected.shape() {
        return Err("vision reference shape differs".into());
    }
    let a = actual.as_array().evaluated()?.try_to_vec::<f32>()?;
    let b = expected.evaluated()?.try_to_vec::<f32>()?;
    let mut maximum = 0f64;
    let mut delta = 0f64;
    let mut norm = 0f64;
    let mut finite = true;
    for (a, b) in a.iter().zip(&b) {
        finite &= a.is_finite() && b.is_finite();
        let difference = f64::from(*a) - f64::from(*b);
        maximum = maximum.max(difference.abs());
        delta += difference * difference;
        norm += f64::from(*b) * f64::from(*b);
    }
    Ok(
        json!({"shape":actual.shape(),"maximum_absolute_error":maximum,
        "relative_l2":delta.sqrt()/norm.sqrt().max(1e-12),"finite":finite,"passed":finite && maximum<=atol}),
    )
}

fn main() -> Result<(), Box<dyn Error>> {
    let args = Args::parse();
    let config: Value =
        serde_json::from_slice(&std::fs::read(args.checkpoint.join("config.json"))?)?;
    let declaration = Declaration::new(
        serde_json::from_value(config["vision_config"].clone())?,
        ProjectorConfig::from_config_value(&config)?,
        "model.vision_tower",
        "model.multi_modal_projector",
    )?;
    let catalog = SafetensorsMetadataCatalog::discover(&args.checkpoint)?;
    let resolution = resolve_safetensors_plan(&catalog, &declaration.safetensors_plan()?)
        .map_err(|e| format!("vision checkpoint admission: {e:?}"))?;
    let source = open_prepared_safetensors_source(
        catalog.admitted_shards(),
        catalog.tensors().clone(),
        resolution,
        2,
    )?;
    let context = ExecutionContext::new(Device::new(
        if args.device == "gpu" {
            DeviceType::Gpu
        } else {
            DeviceType::Cpu
        },
        0,
    ));
    let stream = context.stream();
    let io_context = ExecutionContext::new(Device::new(DeviceType::Cpu, 0));
    let source_stream = io_context.stream();
    let metadata: Value =
        serde_json::from_slice(&std::fs::read(args.reference.join("reference.json"))?)?;
    if metadata["derived_sha256"] != sha256_file(&args.checkpoint.join("model.safetensors"))? {
        return Err("native vision weights differ from the reference's exact F32 artifact".into());
    }
    let reference =
        Array::load_safetensors(args.reference.join("reference.safetensors"), source_stream)?;
    let atol = metadata["maximum_absolute_tolerance"]
        .as_f64()
        .ok_or("missing reference tolerance")?;
    let mut results = Vec::new();
    for case in metadata["cases"]
        .as_array()
        .ok_or("missing reference cases")?
    {
        let name = case["id"].as_str().ok_or("missing case identity")?;
        let grid: Vec<(i32, i32, i32)> = serde_json::from_value(case["grid"].clone())?;
        let shapes: Vec<[usize; 3]> = serde_json::from_value(case["frames"].clone())?;
        let mut packed = Vec::new();
        for (item, [count, height, width]) in shapes.into_iter().enumerate() {
            let rgb = reference[&format!("{name}.rgb.{item}")]
                .evaluated()?
                .try_to_vec::<u8>()?;
            let mut normalized = Vec::new();
            for time in 0..count {
                let mut pixels = Vec::with_capacity(height * width * 3);
                for pixel in 0..height * width {
                    for channel in 0..3 {
                        pixels.push(rgb[(time * 3 + channel) * height * width + pixel]);
                    }
                }
                normalized.push(eredu_media::image::rescale_and_normalize_rgb8(
                    eredu_media::image::RgbImageView::packed(&pixels, width as u32, height as u32)?,
                    1.0 / 255.0,
                    [0.5; 3],
                    [0.5; 3],
                )?);
            }
            let patches = eredu_media::patches::SpatiotemporalPatchSpec {
                patch_size: declaration.config().patch_size as usize,
                temporal_patch_size: declaration.config().temporal_patch_size as usize,
                merge_size: declaration.config().spatial_merge_size as usize,
            }
            .pack(&normalized)?;
            if patches.grid()
                != [
                    grid[item].0 as usize,
                    grid[item].1 as usize,
                    grid[item].2 as usize,
                ]
            {
                return Err("host patch grid differs".into());
            }
            packed.extend_from_slice(patches.values());
        }
        let expected = &reference[&format!("{name}.patches")];
        let pixels = MlxTensor::from_f32_slice(&packed, expected.shape(), stream)?;
        let packing = compare(&pixels, expected, 0.0)?;
        let (mut hidden, state) = {
            let mut patchifier = VisionPatchifier::<Backend>::new(&declaration, stream)?;
            load(&mut patchifier, source.as_ref(), source_stream, stream)?;
            let result = patchifier.forward(
                VisionInput {
                    pixels: &pixels,
                    grid: &grid,
                },
                stream,
            )?;
            let _ = result.0.as_array().evaluated()?;
            result
        };
        for layer in 0..declaration.config().num_hidden_layers {
            let mut block = VisionBlock::<Backend>::new(&declaration, layer, stream)?;
            load(&mut block, source.as_ref(), source_stream, stream)?;
            hidden = block.forward(&hidden, &state, stream)?;
            let _ = hidden.as_array().evaluated()?;
        }
        let encoder = compare(&hidden, &reference[&format!("{name}.hidden")], atol)?;
        let mut projector = VisionProjector::<Backend>::new(&declaration, stream)?;
        load(&mut projector, source.as_ref(), source_stream, stream)?;
        let projected = projector.forward(&hidden, &state, stream)?;
        let projection = compare(&projected, &reference[&format!("{name}.projected")], atol)?;
        results.push(json!({"id":name,"packing":packing,"encoder":encoder,"projector":projection}));
    }
    let passed = results.iter().all(|r| {
        ["packing", "encoder", "projector"]
            .iter()
            .all(|k| r[k]["passed"] == true)
    });
    std::fs::write(
        &args.output,
        serde_json::to_vec_pretty(&json!({"device":args.device,"dtype":"float32",
        "revision":metadata["revision"],"derived_sha256":metadata["derived_sha256"],
        "maximum_absolute_tolerance":atol,"cases":results,"passed":passed}))?,
    )?;
    println!("output={} passed={passed}", args.output.display());
    if !passed {
        return Err("vision component parity failed".into());
    }
    Ok(())
}
