//! Logical semantic history retained by controlled delivery, separate from a
//! consumer's encoded trace. Allocator capacity/overhead is not measured here.

/// Bounds additional history after the already-retained prefix has been counted.
///
/// `Delivery::send` charges a complete record before retaining its semantic
/// event. Parsed argument containers can occupy more logical storage than their
/// JSON encoding: each encoded byte can introduce a value or object entry.
/// For tool-enabled streams, bound future history by that expansion, including
/// string and entry metadata. Text-only streams retain the encoded-byte bound.
/// Nonsemantic records also consume trace capacity, making this conservative.
/// Restore never refunds emitted bytes. A fresh branch uses zero emitted bytes;
/// its source reservation accounts for the inherited history independently.
pub(super) fn semantic_history_growth_bound(
    trace_limit: u64,
    emitted_bytes: u64,
    tool_calls: bool,
) -> u64 {
    trace_limit
        .saturating_sub(emitted_bytes)
        .saturating_mul(if tool_calls {
            crate::runtime::generation::storage::JSON_STORAGE_PER_BYTE
        } else {
            1
        })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::api::{
        ControlledGenerationRecord, ObservedGenerationEvent, ObservedGenerationRecord,
    };
    use crate::runtime::generation::storage::SnapshotStorage;
    use eredu_core::{FinishReason, SemanticEvent};
    use eredu_runtime::execution_control::{TraceBudget, TraceLimits};

    // Minimize attribution and numeric widths rather than relying on the long IDs
    // currently generated by the facade. Escaping and longer fields only add bytes.
    fn record(event: SemanticEvent) -> ControlledGenerationRecord {
        ControlledGenerationRecord {
            schema_version: 0,
            sequence: 0,
            epoch: 0,
            timing: Default::default(),
            generation: ObservedGenerationRecord {
                schema_version: 0,
                run_id: String::new(),
                artifact_identity: None,
                session_id: String::new(),
                capture_plan_id: String::new(),
                intervention_plan_id: None,
                parameter_overlay_id: None,
                event: ObservedGenerationEvent::Semantic {
                    prediction_index: Some(0),
                    event,
                },
            },
        }
    }

    #[test]
    fn semantic_history_is_bounded_by_charged_records_for_every_event_variant() {
        let mut events = Vec::new();
        for arguments in [
            serde_json::json!({}),
            serde_json::json!({"items": [0, 0, 0], "nested": {"": [true, null, {}]}, "text": "é🙂"}),
            serde_json::json!({"items": vec![0; 4096]}),
        ] {
            events.push(SemanticEvent::ToolCallCompleted {
                index: 0,
                id: String::new(),
                name: String::new(),
                arguments: arguments.as_object().unwrap().clone(),
            });
        }
        for reason in [
            FinishReason::Eos,
            FinishReason::StopSequence,
            FinishReason::GrammarComplete,
            FinishReason::MaxTokens,
            FinishReason::Cancelled,
        ] {
            events.push(SemanticEvent::Finished { reason });
        }
        for value in [
            String::new(),
            "a".into(),
            "\"\\\n\0é🙂".into(),
            "x".repeat(65536),
        ] {
            events.extend([
                SemanticEvent::TextDelta(value.clone()),
                SemanticEvent::ReasoningDelta(value.clone()),
                SemanticEvent::ToolCallStart {
                    index: 0,
                    id: value.clone(),
                    name: value.clone(),
                },
                SemanticEvent::ToolArgumentsDelta {
                    index: 0,
                    json_fragment: value,
                },
            ]);
        }
        let limits = TraceLimits {
            per_record_bytes: 1 << 20,
            total_bytes: 64 << 20,
        };
        let mut budget = TraceBudget::new(limits);
        let mut retained = 0;
        for event in events {
            let logical = event.snapshot_bytes().unwrap();
            let record = record(event);
            let before = budget.emitted_bytes();
            budget.charge(&record).unwrap();
            let charged = budget.emitted_bytes() - before;
            assert!(
                logical <= semantic_history_growth_bound(charged, 0, true),
                "{logical} retained bytes exceed {charged} charged bytes: {:?}",
                record.generation.event
            );
            retained += logical;
            assert!(
                retained
                    + semantic_history_growth_bound(
                        limits.total_bytes,
                        budget.emitted_bytes(),
                        true
                    )
                    <= semantic_history_growth_bound(limits.total_bytes, 0, true)
            );
        }
        assert_eq!(
            semantic_history_growth_bound(limits.total_bytes, limits.total_bytes, true),
            0
        );
        assert_eq!(semantic_history_growth_bound(0, 1, true), 0);
        assert_eq!(semantic_history_growth_bound(u64::MAX, 0, true), u64::MAX);
    }
}
